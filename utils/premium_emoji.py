def get_fallback(key: str) -> str:
    """ایموجی معمولی فالبک رو برمیگردونه - برای استفاده مستقیم تو متن ساده"""
    return FALLBACK_EMOJI.get(key, "")


def build_premium_entities(text: str, placeholders: list[tuple[str, str]]) -> tuple[str, list[MessageEntity]]:
    """
    متن نهایی + لیست entity های ایموجی پرمیوم رو میسازه.

    text: متنی که داخلش جاهای خالی برای ایموجی گذاشته شده (با ایموجی فالبک معمولی)
    placeholders: لیستی از (فالبک_ایموجی_که_تو_متن_هست, کلید_ایموجی_پرمیوم)
                  مثلاً [("💰", "money_bag"), ("🍰", "cake")]

    خروجی: (همون متن بدون تغییر, لیست MessageEntity های custom_emoji که باید
    موقع فرستادن پیام با پارامتر entities پاس داده بشن)

    نکته: چون آفست باید بر اساس UTF-16 code units باشه (نه index ساده پایتون)،
    این تابع خودش محاسبه میکنه. برای امن بودن، فقط جاهایی که فالبک ایموجی
    *یکتا* تو متن هست رو جایگزین کن، وگرنه اولین رخداد هر ایموجی استفاده میشه.
    """
    entities = []
    search_start = 0

    for fallback_char, emoji_key in placeholders:
        premium_id = PREMIUM_EMOJI_MAP.get(emoji_key)
        if not premium_id:
            continue

        idx = text.find(fallback_char, search_start)
        if idx == -1:
            idx = text.find(fallback_char)  # اگه بعد از search_start نبود، از اول بگرد
        if idx == -1:
            continue  # این ایموجی تو متن نیست، ردش کن

        # محاسبه آفست به UTF-16 code units (ایموجی‌ها اغلب surrogate pair دارن = طول 2)
        utf16_offset = len(text[:idx].encode("utf-16-le")) // 2
        utf16_length = len(fallback_char.encode("utf-16-le")) // 2

        entities.append(
            MessageEntity(
                type="custom_emoji",
                offset=utf16_offset,
                length=utf16_length,
                custom_emoji_id=premium_id,
            )
        )
        search_start = idx + len(fallback_char)

    return text, entities
