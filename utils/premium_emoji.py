# ایموجی‌های پرمیوم تلگرام برای استفاده تو پیام‌های ربات جوجو.
#
# نکته‌ی مهم فنی: طبق مستندات تلگرام، ارسال ایموجی پرمیوم (custom_emoji) از طریق بات
# فقط زمانی کار میکنه که مالک بات (owner) اشتراک تلگرام پرمیوم داشته باشه.
# اگه اشتراک پرمیوم مالک لغو بشه، این ایموجی‌ها دیگه نمایش داده نمیشن (فقط ایموجی
# جایگزین/فالبک نشون داده میشه) - این محدودیت خود تلگرامه، نه چیزی تو کد ما.
#
# هر ایموجی پرمیوم رو باید با یک ایموجی معمولی «فالبک» جفت کرد؛ تلگرام از این فالبک
# برای کلاینت‌های قدیمی یا زمانی که ایموجی پرمیوم قابل نمایش نیست استفاده میکنه.

from aiogram.types import MessageEntity

# نگاشت اسم معنایی -> آیدی ایموجی پرمیوم
# این آیدی‌ها از پک واقعی «Telegram Ducks» استخراج شدن، به همراه ایموجی دقیق هرکدوم
# (یعنی مطمئنیم هر آیدی واقعاً همون ایموجیه که کنارش نوشته شده - نه حدسی).
# فقط کلیدهایی اینجا هستن که تو همین پک معادل مشخص و مناسب داشتن؛ چون پک تخصصی
# جوجو (کارخونه/شهر/قاچاق و امثالش) نیست، برخی مفاهیم (کارخونه، شهر، صندلی، محصولات
